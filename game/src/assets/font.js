const FALLBACK = G["?"];

export function textWidth(text, scale = 1) {
  return Math.max(0, String(text).length * 6 * scale - scale);
}

export function drawPixelText(ctx, text, x, y, color, opts = {}) {
  const { align = "left", scale = 1, shadow = null } = opts;
  const str = String(text).toUpperCase();
  const w = textWidth(str, scale);
  let ox = Math.round(x);
  if (align === "center") ox = Math.round(x - w / 2);
  if (align === "right") ox = Math.round(x - w);
  const oy = Math.round(y);
  for (let i = 0; i < str.length; i++) {
    const glyph = G[str[i]] || FALLBACK;
    for (let r = 0; r < 7; r++) {
      const row = glyph[r];
      for (let c = 0; c < 5; c++) {
        if (row[c] !== "#") continue;
        const px = ox + i * 6 * scale + c * scale;
        const py = oy + r * scale;
        if (shadow) rect(ctx, px + scale, py + scale, scale, scale, shadow);
        rect(ctx, px, py, scale, scale, color);
      }
    }
  }
  return w;
}
